def css_asset_url(path: Path, css_path: Path) -> str:
    try:
        rel = path.resolve().relative_to(css_path.parent.resolve())
        return rel.as_posix().replace(" ", "%20")
    except ValueError:
        return path.resolve().as_uri()


def mm(value: float) -> str:
    text = f"{value:.2f}".rstrip("0").rstrip(".")
    return f"{text}mm"


def pt(value: float) -> str:
    text = f"{value:.2f}".rstrip("0").rstrip(".")
    return f"{text}pt"


def _chapter_break_css(spec: PrintSpec) -> str:
    if spec.chapter_start == "recto":
        return "break-before: right;\n  page-break-before: right;"
    return "break-before: page;\n  page-break-before: always;"


